
#!/bin/bash

# Nuxus Beget Packager v1.1
# Скрипт для сборки и упаковки проекта в один файл для удобной загрузки.

echo "🚀 Начинаю сборку Ядра для Beget..."

# 1. Удаление старых сборок, чтобы не запутаться
rm -rf out
rm -f nuxus-beget-deploy.zip

# 2. Сборка проекта (именно эта команда создает папку 'out')
echo "⚙️ Выполняю команду npm run build..."
npm run build

# Проверка, создалась ли папка
if [ ! -d "out" ]; then
    echo "❌ Ошибка: Папка 'out' не была создана. Убедитесь, что в терминале нет ошибок выше."
    exit 1
fi

echo "✅ Папка 'out' успешно создана. Упаковываю её содержимое в архив..."

# 3. Упаковка содержимого папки out
# Мы заходим внутрь out, чтобы в архиве не было лишней вложенности
cd out && zip -r ../nuxus-beget-deploy.zip . && cd ..

echo "--------------------------------------------------------"
echo "🎉 ГОТОВО!"
echo "📂 ФАЙЛ ДЛЯ ЗАГРУЗКИ: nuxus-beget-deploy.zip"
echo "📍 ОН ПОЯВИЛСЯ В КОРНЕВОЙ ПАПКЕ ПРОЕКТА."
echo "🚀 ДЕЙСТВИЕ: Скачайте этот файл и распакуйте его"
echo "🚀 в папку public_html на вашем Beget."
echo "--------------------------------------------------------"
