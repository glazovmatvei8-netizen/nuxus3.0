
#!/bin/bash

# Nuxus Beget Packager v1.0
# Скрипт для сборки и упаковки проекта в один файл для удобной загрузки.

echo "🚀 Начинаю сборку Ядра для Beget..."

# 1. Удаление старых сборок
rm -rf out
rm -f nuxus-beget-deploy.zip

# 2. Сборка проекта
npm run build

if [ ! -d "out" ]; then
    echo "❌ Ошибка: Папка 'out' не создана. Проверьте ошибки npm run build выше."
    exit 1
fi

echo "✅ Сборка завершена. Упаковываю в архив..."

# 3. Упаковка содержимого папки out (без самой папки)
cd out && zip -r ../nuxus-beget-deploy.zip . * && cd ..

echo "--------------------------------------------------------"
echo "🎉 ГОТОВО!"
echo "📂 Файл для загрузки: nuxus-beget-deploy.zip"
echo "🚀 ДЕЙСТВИЕ: Скачайте этот архив и распакуйте его"
echo "🚀 прямо в папку public_html на вашем Beget."
echo "--------------------------------------------------------"
