#!/bin/bash

# Nuxus Beget Packager v1.5
# Скрипт для генерации папки out и создания архива для хостинга.

echo "🚀 Запуск процесса сборки Nuxus 3.0..."

# Очистка старых данных
rm -rf .next
rm -rf out
rm -f nuxus-deploy.zip

# Выполнение сборки
echo "⚙️ Выполняю команду npm run build..."
npm run build

# Проверка результата
if [ -d "out" ]; then
    echo "✅ Папка 'out' успешно создана!"
    echo "📦 Упаковываю содержимое в nuxus-deploy.zip..."
    
    # Заходим в папку out, чтобы архив не содержал лишних вложенных папок
    cd out
    zip -r ../nuxus-deploy.zip ./*
    cd ..

    echo "--------------------------------------------------------"
    echo "🎉 ГОТОВО! Файл 'nuxus-deploy.zip' создан."
    echo "🚀 Загрузите содержимое этого архива в public_html на Beget."
    echo "--------------------------------------------------------"
else
    echo "❌ Ошибка: Папка 'out' не появилась. Проверьте логи выше."
    exit 1
fi
